/** The province of a destination, or "Other destinations" for one not on the list yet. */
export function provinceOf(destination: string): string {
  return DESTINATION_PROVINCE[destination.trim().toUpperCase()] ?? "Other destinations";
}

export function regionOf(province: string): Region {
  return PROVINCE_REGION[province] ?? "Other";
}

